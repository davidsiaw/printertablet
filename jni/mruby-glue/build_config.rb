# mruby build for Printer Tablet.
#
# Run on the host (see Makefile.common, target `mruby`):
#   MRUBY_CONFIG=jni/mruby-glue/build_config.rb MRUBY_BUILD_DIR=jni/mruby-glue/build \
#     ruby jni/mruby-cpp/mruby/minirake
#
# Produces:
#   jni/mruby-glue/build/host/lib/libmruby.a   - linked by the desktop build
#   jni/mruby-glue/build/host/include, mrblib/, mrbgems/*/gem_init.c
#       - generated C that jni/mruby-glue/Android.mk compiles with the NDK, so the
#         Android library has exactly the same gems as the desktop one.
#
# Keep the gem list portable to Android 2.3 (API 10): no mruby-cmath
# (needs <complex.h>), no io/socket/dir (we do our own networking).

MRuby::Build.new do |conf|
  conf.toolchain :gcc

  conf.gembox 'stdlib'
  conf.gembox 'stdlib-ext'
  conf.gem core: 'mruby-math'
  conf.gem core: 'mruby-rational'
  conf.gem core: 'mruby-complex'
  conf.gem core: 'mruby-bigint'
  conf.gembox 'metaprog'          # includes mruby-compiler: load .rb source at runtime
  conf.gem core: 'mruby-print'    # print/puts/p (redirected to logcat on Android)
  conf.gem File.expand_path('../mruby-json', __dir__)   # JSON.parse / JSON.generate (submodule)

  # Host tool only (compiles the gems' Ruby code); not part of libmruby.
  conf.gem core: 'mruby-bin-mrbc'
end

# `minirake sources_mk` (after `all`): write the exact C sources, defines
# and include paths that went into libmruby.a, as paths relative to this
# directory. jni/mruby-glue/Android.mk compiles that list with the NDK, and the
# desktop build takes MRUBY_APP_DEFINES from it.
task :sources_mk do
  require 'pathname'
  build = MRuby.targets['host']
  here = Pathname.new(__dir__)
  rel = ->(path) { Pathname.new(File.expand_path(path)).relative_path_from(here).to_s }

  # Gems from outside mruby (e.g. ../mruby-json) build into mrbgems/<name>/
  # but their sources are in the gem's own folder.
  gem_dirs = build.gems.map { |g| ["mrbgems/#{g.name}/", g.dir] }

  sources = build.libmruby_objs.flatten.map do |obj|
    stem = Pathname.new(obj).relative_path_from(Pathname.new(build.build_dir)).sub_ext('').to_s
    bases = [build.build_dir, MRUBY_ROOT].map { |dir| File.join(dir, stem) }
    gem_dirs.each { |prefix, dir| bases << File.join(dir, stem[prefix.size..-1]) if stem.start_with?(prefix) }
    src = bases.product(%w[.c .cxx .cpp])
               .map { |base, ext| base + ext }
               .find { |f| File.exist?(f) }
    raise "sources_mk: no source for #{obj}" unless src
    rel.(src)
  end

  compilers = [build.cc] + build.gems.map(&:cc)
  # build.defines (e.g. MRB_USE_BIGINT) change mruby's headers, so code that
  # includes them must use them too: exported separately as MRUBY_APP_DEFINES.
  app_defines = build.defines.uniq
  defines = (app_defines + compilers.flat_map(&:defines)).uniq
  includes = compilers.flat_map(&:include_paths).uniq.map(&rel)

  out = File.join(build.build_dir, 'mruby_sources.mk')
  File.write(out, <<~MK)
    # Generated by `minirake sources_mk` from jni/mruby-glue/build_config.rb. Do not edit.
    MRUBY_SRC_FILES := #{sources.join(" \\\n\t")}
    MRUBY_DEFINES := #{defines.join(' ')}
    MRUBY_APP_DEFINES := #{app_defines.join(' ')}
    MRUBY_INCLUDES := #{includes.join(' ')}
  MK
  puts "GEN   #{rel.(out)} (#{sources.size} sources)"
end
